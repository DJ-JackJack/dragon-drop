const ADV = 6;

export function textWidth(text: string, scale = 1): number {
  return (text.length * ADV - 1) * scale;
}

export function drawText(img: RGBAImage, text: string, x0: number, y0: number, rgb: number[], scale = 1) {
  let x = Math.round(x0);
  const y = Math.round(y0);
  const sc = Math.max(1, Math.round(scale));
  for (const ch of text.toUpperCase()) {
    const g = G[ch] ?? G[" "];
    const rows = g.split(" ");
    for (let ry = 0; ry < 7; ry++) {
      for (let rx = 0; rx < 5; rx++) {
        if (rows[ry][rx] !== "1") continue;
        for (let sy = 0; sy < sc; sy++) {
          for (let sx = 0; sx < sc; sx++) {
            const px = x + rx * sc + sx, py = y + ry * sc + sy;
            if (px < 0 || py < 0 || px >= img.w || py >= img.h) continue;
            const o = (py * img.w + px) * 4;
            img.data[o] = rgb[0]; img.data[o + 1] = rgb[1]; img.data[o + 2] = rgb[2];
          }
        }
      }
    }
    x += ADV * sc;
  }
}
