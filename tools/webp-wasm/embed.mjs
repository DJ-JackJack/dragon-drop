// node embed.mjs <webp.wasm> <out.ts> <libwebp version>: writes the module as a deflated, base64 string in a TypeScript file (so it bundles and runs from anywhere: no file to find).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { deflateRawSync } from "node:zlib";

const [, , wasmPath, outPath, version] = process.argv;
const wasm = readFileSync(wasmPath);
const packed = deflateRawSync(wasm, { level: 9 });
const b64 = packed.toString("base64");
const lines = b64.match(/.{1,120}/g).map((l) => `  "${l}",`).join("\n");
writeFileSync(outPath, `/**
 * GENERATED by tools/webp-wasm/build.sh: do not edit. The WebP decoder: libwebp ${version} (BSD-3-Clause, see tools/webp-wasm/LICENSE-libwebp.txt), decoder only,
 * compiled to WebAssembly. Raw-deflated, then base64. ${wasm.length} bytes of WebAssembly, sha256 ${createHash("sha256").update(wasm).digest("hex")}.
 */
export const WEBP_WASM_SHA256 = "${createHash("sha256").update(wasm).digest("hex")}";
export const WEBP_WASM_BYTES = ${wasm.length};
export const LIBWEBP_VERSION = "${version}";
export const WEBP_WASM_BASE64 = [
${lines}
].join("");
`);
console.log(`wrote ${outPath}: ${wasm.length} bytes of wasm, ${packed.length} deflated, ${b64.length} base64`);
